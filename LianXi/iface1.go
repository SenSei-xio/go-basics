package main

import "fmt"

type Student struct {
	Name  string
	Score int
	ID    int
}

// ============================================================
// 【第 1 题】把接口的签名补上
// ============================================================
// 接口花括号里：只写"方法长什么样"，不写 func，不写实现
// 现在下面是空的，你要写成：  保存(s Student)
//
//	格式：  type 存储 interface {
//	            保存(s Student)
//	        }
type 存储 interface {
	保存(s Student) // ← 这里补一行
}

// ============================================================
// 【第 2 题】给 文件存储 写方法
// ============================================================
// 记住：方法写在 struct 花括号【外面】，不在里面
//
//	格式：  func (f 文件存储) 保存(s Student) {
//	            这里打印
//	        }
type 文件存储 struct{ 路径 string }

func (f 文件存储) 保存(s Student) {
	fmt.Println("文件存了", s.Name)
}

// ← 这里补方法

// ============================================================
// 【第 3 题】给 内存存储 写方法（跟上面一模一样，只改打印的话）
// ============================================================
type 内存存储 struct{ 容量 int }

func (f 内存存储) 保存(s Student) {
	fmt.Println("内存存了", s.Name)
}

// ← 这里补方法

// ============================================================
// 下面不用改
// ============================================================
func 备份(s 存储, stu Student) {
	fmt.Println("【备份开始】")
	s.保存(stu)
	fmt.Println("【备份结束】")
}

func main() {
	m := make(map[int]Student)
	m[1] = Student{"小明", 70, 1}

	fmt.Println("=== 传 文件存储 ===")
	备份(文件存储{路径: "students.json"}, m[1])

	fmt.Println()
	fmt.Println("=== 传 内存存储（备份函数一个字都没改）===")
	备份(内存存储{容量: 100}, m[1])
}
