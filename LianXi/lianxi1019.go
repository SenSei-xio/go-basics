package main

import "fmt"

type Student struct {
	Name  string
	Score int
	ID    int
}

// ============================================================
// 练习① 《图纸 vs 盒子》
// 把下面 4 行里凡是空的地方补全，让它们都能编译。
// 目标：分清 []Student（图纸）和 []Student{}（盒子）
// ============================================================

func 练习1() {
	// ① 造一个空盒子（用花括号）
	a := []Student{} // ← 填这里

	// ② 只声明不造（用 var）
	var b []Student // ← 填这里

	// ③ 造一个装着 2 张卡的盒子（字面量）
	c := []Student{{"小明", 70, 1}, {"小紫", 40, 3}} // ← 填这里

	fmt.Println("①", a, len(a))
	fmt.Println("②", b, len(b))
	fmt.Println("③", c, len(c))
}

// ============================================================
// 练习② 《值接收者 vs 指针接收者》
// 方法体在两个版本里都写 s.Score = v（不许改方法体！）
// 只允许改括号里的签名，让"指针版"能真的改到外面。
// 跑完之后应该看到：值版 40（没改到），指针版 100（改到了）
// ============================================================

// 值接收者：不用动
func (s Student) 改值版(v int) {
	s.Score = v
}

// 指针接收者：← 改这一行的括号
func (s *Student) 改指针版(v int) {
	s.Score = v
}

func 练习2() {
	a := Student{"小明", 40, 1}
	a.改值版(100)
	fmt.Println("值版改完，a.Score =", a.Score) // 应该是 40

	b := Student{"小明", 40, 1}
	b.改指针版(100)
	fmt.Println("指针版改完，b.Score =", b.Score) // 应该是 100
}

// ============================================================
// 练习③ 《append 必须接住》
// 下面两段是同一个操作，一段接住了返回值，一段没接住。
// 把 ？？？ 换成正确的写法，让"接住版"真的塞进去。
// ============================================================

func 练习3() {
	var 接住版 []Student
	var 不接住版 []Student

	接住版 = append(接住版, Student{"小明", 70, 1}) // ← 填这里（把 Student{"小明", 70, 1} 塞进去）

	不接住版 = nil // 故意演示错误写法：什么都不做
	//append(不接住版, Student{"小明", 70, 1}) // ← 这行是错的示范，别学

	fmt.Println("接住版：", 接住版, "len =", len(接住版))    // 应该是 [{小明 70 1}] len = 1
	fmt.Println("不接住版：", 不接住版, "len =", len(不接住版)) // 应该是 [] len = 0

	不接住版 = append(不接住版, Student{"小明", 70, 1})
	_ = append(不接住版, Student{"小明", 70, 1})

	fmt.Println("修好之后：", 不接住版, "len =", len(不接住版)) // 应该是 [{小明 70 1}] len = 1
}

func main() {
	fmt.Println("===== 练习① 图纸 vs 盒子 =====")
	练习1()
	fmt.Println()
	fmt.Println("===== 练习② 值接收者 vs 指针接收者 =====")
	练习2()
	fmt.Println()
	fmt.Println("===== 练习③ append 必须接住 =====")
	练习3()
}
